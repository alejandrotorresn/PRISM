#!/bin/bash
set -e

PYTHON_CMD="python"
BASE_OUTPUT_DIR="data/zephyr/results_thesis_mode"
GPU_BUDGETS_MB="400,600,800,1000,1200"
CPU_MEM_BUDGET_MB="1e18"
MEMORY_MODEL="topological"
PEAK_ACTIVATION_OVERLAP="0.35"
K_SIGMA="1.0"
W_TIME="0.5"
W_ENERGY="0.5"
W_TRANSFER="1.0"
BACKEND="auto"
HW_AGGREGATE="max"
HW_DISPERSION_K="0.0"
REGIME="diagnostic"
ENFORCE_CONVEX_WEIGHTS="false"
STRICT_GRAPH_MAPPING="false"
STRICT_TRANSFER_MAPPING="false"
ALLOW_LOW_QUALITY_STATS="true"
ALLOW_TRANSFER_CALIBRATION_FALLBACK="true"
ALLOW_FALLBACK_GRAPH_TRACE="true"

for MODEL in "resnet152" "vit_b16"; do
    CFG="${BASE_OUTPUT_DIR}/${MODEL}/AdamW/fp32/batch_64"
    if [ ! -d "$CFG" ]; then
        echo "WARNING: Config dir not found: $CFG"
        continue
    fi
    echo "Running ILP for $MODEL batch 64..."
    MODEL="$MODEL" \
    CONFIG_DIR="$CFG" \
    PYTHON_CMD="$PYTHON_CMD" \
    K_SIGMA="$K_SIGMA" \
    W_TIME="$W_TIME" \
    W_ENERGY="$W_ENERGY" \
    W_TRANSFER="$W_TRANSFER" \
    GPU_MEM_BUDGET_MB="1e18" \
    CPU_MEM_BUDGET_MB="$CPU_MEM_BUDGET_MB" \
    MEMORY_MODEL="$MEMORY_MODEL" \
    PEAK_ACTIVATION_OVERLAP="$PEAK_ACTIVATION_OVERLAP" \
    BACKEND="$BACKEND" \
    HW_AGGREGATE="$HW_AGGREGATE" \
    HW_DISPERSION_K="$HW_DISPERSION_K" \
    REGIME="$REGIME" \
    ENFORCE_CONVEX_WEIGHTS="$ENFORCE_CONVEX_WEIGHTS" \
    STRICT_GRAPH_MAPPING="$STRICT_GRAPH_MAPPING" \
    STRICT_TRANSFER_MAPPING="$STRICT_TRANSFER_MAPPING" \
    ALLOW_LOW_QUALITY_STATS="$ALLOW_LOW_QUALITY_STATS" \
    ALLOW_TRANSFER_CALIBRATION_FALLBACK="$ALLOW_TRANSFER_CALIBRATION_FALLBACK" \
    ALLOW_FALLBACK_GRAPH_TRACE="$ALLOW_FALLBACK_GRAPH_TRACE" \
    bash scripts/run_ilp_partition.sh

    echo "Running Pareto sweep for $MODEL batch 64..."
    MODEL="$MODEL" \
    CONFIG_DIR="$CFG" \
    PYTHON_CMD="$PYTHON_CMD" \
    GPU_BUDGETS_MB="$GPU_BUDGETS_MB" \
    CPU_MEM_BUDGET_MB="$CPU_MEM_BUDGET_MB" \
    MEMORY_MODEL="$MEMORY_MODEL" \
    PEAK_ACTIVATION_OVERLAP="$PEAK_ACTIVATION_OVERLAP" \
    K_SIGMA="$K_SIGMA" \
    W_TIME="$W_TIME" \
    W_ENERGY="$W_ENERGY" \
    W_TRANSFER="$W_TRANSFER" \
    BACKEND="$BACKEND" \
    HW_AGGREGATE="$HW_AGGREGATE" \
    HW_DISPERSION_K="$HW_DISPERSION_K" \
    REGIME="$REGIME" \
    ENFORCE_CONVEX_WEIGHTS="$ENFORCE_CONVEX_WEIGHTS" \
    STRICT_GRAPH_MAPPING="$STRICT_GRAPH_MAPPING" \
    STRICT_TRANSFER_MAPPING="$STRICT_TRANSFER_MAPPING" \
    ALLOW_LOW_QUALITY_STATS="$ALLOW_LOW_QUALITY_STATS" \
    ALLOW_TRANSFER_CALIBRATION_FALLBACK="$ALLOW_TRANSFER_CALIBRATION_FALLBACK" \
    ALLOW_FALLBACK_GRAPH_TRACE="$ALLOW_FALLBACK_GRAPH_TRACE" \
    bash scripts/run_ilp_pareto_sweep.sh
done
